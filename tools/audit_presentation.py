"""Check maintained presentation terminology, figure provenance and archive scope."""
import argparse
import ast
import hashlib
import json
import re
from pathlib import Path
import xml.etree.ElementTree as ET

from .finalize_bundle import ROOT, included


FORBIDDEN = re.compile(r'\bv(?:12|13)\b|\b(?:new|old) model\b|新模型|旧模型|新架构|本次|本轮|面试|汇报',re.I)


def sha(path):return hashlib.sha256(path.read_bytes()).hexdigest()


def prose(text):
    text=re.sub(r'```.*?```','',text,flags=re.S)
    text=re.sub(r'`[^`\n]+`','',text)
    # Link destinations can contain immutable implementation and experiment IDs.
    return re.sub(r'\]\([^)]+\)',']',text)


def audit():
    docs=[ROOT/'README.md',ROOT/'CONTRIBUTING.md',*sorted((ROOT/'docs').glob('*.md')),
          *sorted((ROOT/'.github').rglob('*.md'))]
    violations=[]
    for path in docs:
        for line_no,line in enumerate(prose(path.read_text(encoding='utf-8')).splitlines(),1):
            if FORBIDDEN.search(line):violations.append({'file':path.relative_to(ROOT).as_posix(),'line':line_no,'text':line})
    asset_root=ROOT/'assets/showcase'
    manifest=json.loads((asset_root/'manifest.json').read_text())
    for name,expected in manifest['artifacts'].items():
        assert sha(asset_root/name)==expected,name
    for name,expected in manifest['input_sha256'].items():
        assert sha(ROOT/name)==expected,name
    labels=[]
    for path in sorted(asset_root.glob('*.svg')):
        label=' '.join(''.join(node.itertext()) for node in ET.parse(path).iter() if node.tag.endswith('}text'))
        labels.append(path.name)
        if FORBIDDEN.search(label):violations.append({'file':path.relative_to(ROOT).as_posix(),'text':'forbidden figure label'})
    html=(asset_root/'explorer.html').read_text(encoding='utf-8')
    if FORBIDDEN.search(html):violations.append({'file':'assets/showcase/explorer.html','text':'forbidden explorer label'})
    # Figure/animation text is generated by these constants; numerical arrays stay unchanged.
    source=ROOT/'examples/field_showcase.py'
    assert sha(source)==manifest['generator_sha256'],'showcase generator changed'
    for node in ast.walk(ast.parse(source.read_text(encoding='utf-8'))):
        if isinstance(node,ast.Constant) and isinstance(node.value,str) and FORBIDDEN.search(node.value):
            violations.append({'file':'examples/field_showcase.py','line':node.lineno,'text':node.value})
    assert 'Hierarchical Recurrent Operator' in (ROOT/'README.md').read_text(encoding='utf-8')
    assert (ROOT/'README.md').read_text(encoding='utf-8').startswith('# SMA-SCIML\n')
    modal_root=ROOT/'assets/hro_modal'
    modal_manifest=json.loads((modal_root/'manifest.json').read_text())
    for name,expected in modal_manifest['artifacts'].items():assert sha(modal_root/name)==expected,name
    for name,expected in modal_manifest['input_sha256'].items():assert sha(ROOT/name)==expected,name
    assert sha(ROOT/'examples/modal_showcase.py')==modal_manifest['generator_sha256']
    for path in sorted(modal_root.glob('*.svg')):
        label=' '.join(''.join(node.itertext()) for node in ET.parse(path).iter() if node.tag.endswith('}text'))
        if FORBIDDEN.search(label):violations.append({'file':path.relative_to(ROOT).as_posix(),'text':'forbidden modal figure label'})
    readout_root=ROOT/'assets/sma_readout_local'
    readout_manifest=json.loads((readout_root/'manifest.json').read_text())
    for name,expected in readout_manifest['artifacts'].items():assert sha(readout_root/name)==expected,name
    for name,expected in readout_manifest['input_sha256'].items():assert sha(ROOT/name)==expected,name
    assert sha(ROOT/'examples/sma_readout_report.py')==readout_manifest['generator_sha256']
    for path in sorted(readout_root.glob('*.svg')):
        label=' '.join(''.join(node.itertext()) for node in ET.parse(path).iter() if node.tag.endswith('}text'))
        if FORBIDDEN.search(label):violations.append({'file':path.relative_to(ROOT).as_posix(),'text':'forbidden readout figure label'})
    stage_root=ROOT/'assets/sma_stage_readout'
    stage_manifest=json.loads((stage_root/'manifest.json').read_text())
    for name,expected in stage_manifest['artifacts'].items():assert sha(stage_root/name)==expected,name
    for name,expected in stage_manifest['input_sha256'].items():assert sha(ROOT/name)==expected,name
    assert sha(ROOT/'examples/stage_readout_report.py')==stage_manifest['generator_sha256']
    for path in sorted(stage_root.glob('*.svg')):
        label=' '.join(''.join(node.itertext()) for node in ET.parse(path).iter() if node.tag.endswith('}text'))
        if FORBIDDEN.search(label):violations.append({'file':path.relative_to(ROOT).as_posix(),'text':'forbidden stage figure label'})
    mean_root=ROOT/'assets/sma_mean_development'
    mean_manifest=json.loads((mean_root/'manifest.json').read_text())
    for name,expected in mean_manifest['artifacts'].items():assert sha(mean_root/name)==expected,name
    for name,expected in mean_manifest['input_sha256'].items():assert sha(ROOT/name)==expected,name
    assert sha(ROOT/'examples/mean_development_report.py')==mean_manifest['generator_sha256']
    for path in sorted(mean_root.glob('*.svg')):
        label=' '.join(''.join(node.itertext()) for node in ET.parse(path).iter() if node.tag.endswith('}text'))
        if FORBIDDEN.search(label):violations.append({'file':path.relative_to(ROOT).as_posix(),'text':'forbidden mean figure label'})
    response_root=ROOT/'assets/sma_relaxation_readout'
    response_manifest=json.loads((response_root/'manifest.json').read_text())
    for name,expected in response_manifest['artifacts'].items():assert sha(response_root/name)==expected,name
    for name,expected in response_manifest['input_sha256'].items():assert sha(ROOT/name)==expected,name
    assert sha(ROOT/'examples/relaxation_report.py')==response_manifest['generator_sha256']
    for path in sorted(response_root.glob('*.svg')):
        label=' '.join(''.join(node.itertext()) for node in ET.parse(path).iter() if node.tag.endswith('}text'))
        if FORBIDDEN.search(label):violations.append({'file':path.relative_to(ROOT).as_posix(),'text':'forbidden response figure label'})
    risk_root=ROOT/'assets/sma_risk_limited_readout'
    risk_manifest=json.loads((risk_root/'manifest.json').read_text())
    for name,expected in risk_manifest['artifacts'].items():assert sha(risk_root/name)==expected,name
    for name,expected in risk_manifest['input_sha256'].items():assert sha(ROOT/name)==expected,name
    assert sha(ROOT/'examples/risk_limited_report.py')==risk_manifest['generator_sha256']
    for path in sorted(risk_root.glob('*.svg')):
        label=' '.join(''.join(node.itertext()) for node in ET.parse(path).iter() if node.tag.endswith('}text'))
        if FORBIDDEN.search(label):violations.append({'file':path.relative_to(ROOT).as_posix(),'text':'forbidden error-scaled response figure label'})
    inventory={}
    for path in sorted(ROOT.rglob('*')):
        if not included(path):continue
        rel=path.relative_to(ROOT).as_posix()
        if path in docs or rel.startswith('assets/showcase/'):
            category='maintained_presentation'
        elif rel.startswith(('archive/','SciML/docs/learning_closed_loop_report/',
                              'assets/operator_showcase_','assets/operator_animation_','assets/v13_formal_v1/')):
            category='historical_presentation_or_notes'
        elif rel.startswith(('data/','checkpoints/','evidence/')):
            category='numerical_evidence_and_provenance'
        else:category='implementation_tests_and_supporting_assets'
        inventory[rel]=category
    if violations:raise ValueError(json.dumps(violations,ensure_ascii=False,indent=2))
    return {'status':'passed_presentation_audit','project':'SMA-SCIML','method':'Hierarchical Recurrent Operator (HRO)',
        'baseline':'Residual MLP + DeepONet','maintained_markdown_files_checked':len(docs),
        'svg_labels_checked':labels,'html_labels_checked':True,'animation_generator_labels_checked':True,
        'showcase_input_and_output_hashes_checked':True,'fresh_training_calls':0,'fresh_solver_calls':0,
        'modal_showcase_input_output_and_label_checks':True,
        'sma_readout_input_output_and_label_checks':True,
        'stage_readout_input_output_and_label_checks':True,
        'mean_readout_input_output_and_label_checks':True,
        'relaxation_readout_input_output_and_label_checks':True,
        'error_scaled_response_input_output_and_label_checks':True,
        'scope':'Maintained prose, generated showcase labels and repository inventory; technical paths and immutable historical evidence retain their identifiers.',
        'browser_rendering_acceptance':'pending; tracked separately from text/array/interaction-logic checks',
        'file_categories':{k:sum(v==k for v in inventory.values()) for k in sorted(set(inventory.values()))},
        'inventory':inventory}


if __name__=='__main__':
    p=argparse.ArgumentParser(description=__doc__);p.add_argument('--output',type=Path);args=p.parse_args()
    result=audit()
    if args.output:
        with args.output.open('x',encoding='utf-8',newline='\n') as f:json.dump(result,f,ensure_ascii=False,indent=2)
    print(json.dumps({k:v for k,v in result.items() if k!='inventory'},ensure_ascii=False,indent=2))
